# Email content builders
# ---------------------------------------------------------------------------


def _build_html_email(reports_markdown: List[dict], schedule_label: str) -> str:
    """Build full HTML email body from a list of OpenRouter markdown reports."""
    now_ist = datetime.now(IST).strftime("%Y-%m-%d %H:%M IST")

    body = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<style>
  body {{ font-family: 'Segoe UI', Arial, sans-serif; background: #0d1117; color: #c9d1d9; margin: 0; padding: 20px; }}
  .container {{ max-width: 900px; margin: 0 auto; }}
  .report-header {{ border-bottom: 2px solid #30363d; padding-bottom: 14px; margin-bottom: 20px; }}
  .report-title {{ color: #58a6ff; font-size: 22px; margin: 0 0 6px; }}
  .meta {{ color: #8b949e; font-size: 13px; }}
  .space-block {{ border: 1px solid #30363d; border-radius: 8px; padding: 18px 22px; margin: 20px 0; background: #161b22; }}
  .error-box {{ color: #f85149; background: #1c0c0c; border: 1px solid #3d1414; padding: 12px; border-radius: 6px; font-size: 13px; }}
  .no-data {{ color: #8b949e; font-style: italic; font-size: 13px; }}
  .footer {{ color: #484f58; font-size: 11px; margin-top: 30px; border-top: 1px solid #21262d; padding-top: 12px; }}
</style>
</head>
<body>
<div class="container">
  <div class="report-header">
    <h1 class="report-title">📊 ClickUp Daily Report — {html.escape(schedule_label)}</h1>
    <p class="meta">Generated: {now_ist}&nbsp;&nbsp;|&nbsp;&nbsp;Reports via OpenRouter + ClickUp MCP (identical to localhost page)</p>
  </div>
"""

    for entry in reports_markdown:
        space = entry.get("space", "Unknown")
        error = entry.get("error")
        markdown = (entry.get("markdown") or "").strip()

        body += '<div class="space-block">'

        if error:
            body += f'<h2 style="color:#f85149;font-size:17px;margin:0 0 12px;">🔴 {html.escape(space)}</h2>'
            body += f'<div class="error-box"><strong>Error:</strong> {html.escape(str(error))}</div>'
        elif not markdown:
            body += f'<h2 style="color:#79c0ff;font-size:17px;margin:0 0 12px;">📁 {html.escape(space)}</h2>'
            body += '<p class="no-data">No report data was returned for this space.</p>'
        else:
            # Render the exact markdown the OpenRouter model produced
            body += _render_markdown(markdown)

        body += "</div>\n"

    body += (
        '<div class="footer">'
        "Auto-generated by ClickUp Motia Reports &bull; Powered by OpenRouter + ClickUp MCP"
        "</div>"
    )
    body += "\n</div></body></html>"
    return body


def _build_combined_md(reports_markdown: List[dict], schedule_label: str) -> str:
    """Build a combined .md attachment from all space reports."""
    now_ist = datetime.now(IST).strftime("%Y-%m-%d %H:%M IST")
    parts = [
        f"# ClickUp Daily Report — {schedule_label}",
        "",
        f"Generated: {now_ist}",
        "",
        "---",
        "",
    ]

    for entry in reports_markdown:
        space = entry.get("space", "Unknown")
        error = entry.get("error")
        markdown = (entry.get("markdown") or "").strip()

        if error:
            parts += [f"## ❌ {space}", "", f"**Error:** {error}", "", "---", ""]
        elif not markdown:
            parts += [f"## {space}", "", "_No report data received._", "", "---", ""]
        else:
            parts += [markdown, "", "---", ""]

    return "\n".join(parts)


