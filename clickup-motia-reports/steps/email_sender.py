"""
Email Formatter & Sender — renders OpenRouter-generated markdown reports into HTML email.

The markdown content passed here is the exact same markdown that is displayed on the
localhost web UI (generated by OpenRouter + ClickUp MCP tools). This ensures the email
report is identical to what you see on the local page.
"""

import html
import re
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.mime.base import MIMEBase
from email import encoders
from datetime import datetime, timezone, timedelta
from typing import List

IST = timezone(timedelta(hours=5, minutes=30))


# ---------------------------------------------------------------------------
# Markdown → HTML renderer (matches the style of the api_server.py web UI)
# ---------------------------------------------------------------------------


def _md_inline(text: str) -> str:
    """Convert inline markdown (bold, italic, inline-code) to HTML."""
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"__(.+?)__", r"<strong>\1</strong>", text)
    text = re.sub(r"\*(.+?)\*", r"<em>\1</em>", text)
    text = re.sub(
        r"`(.+?)`",
        r'<code style="background:#21262d;padding:2px 6px;border-radius:4px;">\1</code>',
        text,
    )
    return text


def _render_markdown(markdown: str) -> str:
    """Convert a markdown string to styled HTML matching the localhost page aesthetic."""
    lines = (markdown or "").splitlines()
    out: List[str] = []
    i = 0

    while i < len(lines):
        raw = lines[i]
        stripped = raw.strip()

        # Blank line
        if not stripped:
            i += 1
            continue

        # Horizontal rule
        if re.match(r"^[-*_]{3,}\s*$", stripped):
            out.append(
                '<hr style="border:0;border-top:1px solid #30363d;margin:16px 0;">'
            )
            i += 1
            continue

        # ATX headings
        m = re.match(r"^(#{1,6})\s+(.*)", stripped)
        if m:
            level = len(m.group(1))
            content = _md_inline(html.escape(m.group(2).strip()))
            col = {1: "#58a6ff", 2: "#79c0ff", 3: "#d2a8ff"}.get(level, "#c9d1d9")
            sz = {1: "20px", 2: "17px", 3: "15px"}.get(level, "13px")
            mt = {1: "22px", 2: "18px", 3: "14px"}.get(level, "10px")
            out.append(
                f'<h{level} style="color:{col};font-size:{sz};margin:{mt} 0 8px;'
                f'border-bottom:1px solid #30363d;padding-bottom:6px;">{content}</h{level}>'
            )
            i += 1
            continue

        # Table (header row followed by divider row)
        if "|" in stripped and i + 1 < len(lines):
            next_stripped = lines[i + 1].strip()
            if re.match(r"^[\s|:\-]+$", next_stripped) and "|" in next_stripped:
                headers = [c.strip() for c in stripped.strip("|").split("|")]
                i += 2  # skip header + divider
                rows: List[List[str]] = []
                while i < len(lines) and "|" in lines[i]:
                    cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                    rows.append(cells)
                    i += 1

                t = (
                    '<table style="border-collapse:collapse;width:100%;margin:10px 0 20px 0;'
                    'background:#161b22;border-radius:6px;overflow:hidden;">'
                    "<thead><tr>"
                )
                for h in headers:
                    t += (
                        '<th style="background:#21262d;color:#58a6ff;padding:10px 14px;'
                        'text-align:left;font-size:13px;border-bottom:1px solid #30363d;">'
                        f"{html.escape(h)}</th>"
                    )
                t += "</tr></thead><tbody>"
                for row in rows:
                    t += "<tr>"
                    for cell in row:
                        t += (
                            '<td style="padding:8px 14px;border-bottom:1px solid #21262d;'
                            f'font-size:13px;color:#c9d1d9;">{_md_inline(html.escape(cell))}</td>'
                        )
                    t += "</tr>"
                t += "</tbody></table>"
                out.append(t)
                continue

        # Unordered list
        if re.match(r"^[-*+]\s+", stripped):
            items: List[str] = []
            while i < len(lines) and re.match(r"^[-*+]\s+", lines[i].strip()):
                item_text = re.sub(r"^[-*+]\s+", "", lines[i].strip())
                items.append(
                    f'<li style="margin:4px 0;color:#c9d1d9;">'
                    f"{_md_inline(html.escape(item_text))}</li>"
                )
                i += 1
            out.append(
                '<ul style="margin:8px 0 12px 20px;padding:0;">'
                + "".join(items)
                + "</ul>"
            )
            continue

        # Ordered list
        if re.match(r"^\d+\.\s+", stripped):
            items = []
            while i < len(lines) and re.match(r"^\d+\.\s+", lines[i].strip()):
                item_text = re.sub(r"^\d+\.\s+", "", lines[i].strip())
                items.append(
                    f'<li style="margin:4px 0;color:#c9d1d9;">'
                    f"{_md_inline(html.escape(item_text))}</li>"
                )
                i += 1
            out.append(
                '<ol style="margin:8px 0 12px 20px;padding:0;">'
                + "".join(items)
                + "</ol>"
            )
            continue

        # Paragraph
        out.append(
            f'<p style="margin:6px 0;color:#c9d1d9;font-size:13px;">'
            f"{_md_inline(html.escape(stripped))}</p>"
        )
        i += 1

    return "\n".join(out)


